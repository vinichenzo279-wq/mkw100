using System.Collections.Frozen;
using System.Globalization;
using Translator.Core.Disassembly;
using Translator.Core.Ir;

namespace Translator.Core.Lifting;

/// <summary>
/// mkw100: `mulli rD, rA, 0xF0` instructions that index RacedataScenario player slots. The lifter
/// turns each into a call to <see cref="Helper"/> (runtime/include/guest_abi/player_slots.h), which
/// returns rA * 0xF0 for slots 0..11 and an address delta into the overflow region for slots 12+,
/// so the game's inline 12-slot array stays where it is (docs/mkw100/DESIGN.md).
///
/// <b>Deref</b> sites are the loads and stores of an unrolled loop's slot pointer: CodeWarrior
/// unrolls `for (i = 0; i &lt; count; ++i)` 8 or 6 ways into one product for player i plus fixed
/// displacements reaching players i+1..i+7, which the product alone cannot move. Each listed
/// D-form access (or `addi` forming a Player*) gets its effective address from
/// <see cref="AddressHelper"/>(rA, d) instead of rA + d; the helper resolves the pointer back to
/// player i and its scenario and returns the address of the field in player i + k's slot.
///
/// The list is generated by scripts/mkw100/slot_sites.py and named by the project's
/// `translation.player_slot_sites`. Process-wide like <see cref="GuestSaveRestoreThunks"/>: one
/// project per translator run.
/// </summary>
public sealed class PlayerSlotStrideSites
{
    public const string Helper = "MKW100_PlayerSlotOffset";
    public const string AddressHelper = "MKW100_PlayerSlotAddress";
    public const int Stride = 0xF0;

    public static PlayerSlotStrideSites Current { get; set; } = new(FrozenSet<uint>.Empty);

    private readonly FrozenSet<uint> _sites;
    private readonly FrozenSet<uint> _derefs;

    public PlayerSlotStrideSites(IEnumerable<uint> sites, IEnumerable<uint>? derefs = null)
    {
        _sites = sites.ToFrozenSet();
        _derefs = (derefs ?? Array.Empty<uint>()).ToFrozenSet();
    }

    public int Count => _sites.Count;

    public int DerefCount => _derefs.Count;

    public bool Contains(uint address) => _sites.Contains(address);

    /// <summary>The lifted IR of <paramref name="ins"/>, rewritten when it is a listed deref site.</summary>
    public IReadOnlyList<IrInstruction> RewriteDeref(PpcInstruction ins, IReadOnlyList<IrInstruction> ir)
    {
        if (!_derefs.Contains(ins.Address))
            return ir;
        var word = ins.Word;
        var op = (int)(word >> 26);
        var rd = (int)((word >> 21) & 31);
        var ra = (int)((word >> 16) & 31);
        var displacement = (int)(short)(word & 0xFFFF);
        string Where() => $"player slot deref 0x{ins.Address:X8} ({ins.Mnemonic})";
        if (ra == 0)
            throw new InvalidOperationException($"{Where()}: rA is r0");
        var address = $"addr_slot_{ins.Address:X8}_loc";
        var call = new IrCall(address, AddressHelper, new[] { IrValue.Register($"r{ra}"), IrValue.Imm(displacement) });

        if (op == 14)  // addi rD, rA, d: the Player* (or field pointer) itself
            return new IrInstruction[] { call, new IrAssign($"r{rd}", IrValue.Register(address)) };

        // lwz lbz stw stb lhz lha sth (no update forms: those write rA back)
        if (op is not (32 or 34 or 36 or 38 or 40 or 42 or 44) || ir.Count != 1)
            throw new InvalidOperationException($"{Where()}: not a plain D-form load or store");
        var expected = new IrAddress($"r{ra}", displacement);
        return ir[0] switch
        {
            IrLoad load when load.Address == expected =>
                new IrInstruction[] { call, load with { Address = new IrAddress(address, 0) } },
            IrStore store when store.Address == expected =>
                new IrInstruction[] { call, store with { Address = new IrAddress(address, 0) } },
            _ => throw new InvalidOperationException($"{Where()}: lifted to {ir[0].Kind}, not a load/store off r{ra}+{displacement}")
        };
    }

    /// <summary>
    /// One `0x80xxxxxx` per line: a mulli site, or with a second field `deref` a deref site;
    /// `#` starts a comment.
    /// </summary>
    /// <param name="profile">The translate-mod profile; lines tagged `profile=NAME` apply only to it.</param>
    public static PlayerSlotStrideSites Load(string path, string? profile = null)
    {
        var sites = new List<uint>();
        var derefs = new List<uint>();
        foreach (var (raw, index) in File.ReadLines(path).Select((line, i) => (line, i)))
        {
            var text = raw.Split('#', 2)[0].Trim();
            if (text.Length == 0)
                continue;
            var all = text.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries);
            var siteProfile = all.Where(f => f.StartsWith("profile=", StringComparison.Ordinal))
                .Select(f => f["profile=".Length..]).SingleOrDefault();
            var fields = all.Where(f => !f.StartsWith("profile=", StringComparison.Ordinal)).ToArray();
            if (siteProfile is not null && !string.Equals(siteProfile, profile, StringComparison.OrdinalIgnoreCase))
                continue;
            if (!fields[0].StartsWith("0x", StringComparison.OrdinalIgnoreCase)
                || !uint.TryParse(fields[0].AsSpan(2), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var address))
                throw new FormatException($"{path}:{index + 1}: expected a 0x-prefixed guest address, got '{text}'");
            if (fields.Length == 1)
                sites.Add(address);
            else if (fields.Length == 2 && fields[1] == "deref")
                derefs.Add(address);
            else
                throw new FormatException($"{path}:{index + 1}: expected an address and optionally `deref`, got '{text}'");
        }
        return new PlayerSlotStrideSites(sites, derefs);
    }
}
