using System.Collections.Frozen;
using System.Globalization;
using Translator.Core.Disassembly;
using Translator.Core.Ir;

namespace Translator.Core.Lifting;

/// <summary>
/// mkw100: instructions that index a per-player `[12]` array inside a singleton object. Element
/// i >= 12 of a class's arrays lives in a shadow window laid out like the object
/// (runtime/include/guest_abi/array_overflow.h); two rewrites send the game's own address math
/// there and leave elements 0..11 exactly where they were:
/// <list type="bullet">
/// <item><b>scale</b>: `mulli rD, rA, stride` or `rlwinm rD, rS, log2(stride), MB, ME` keeps its
/// result and is followed by rD = <see cref="IndexScaledHelper"/>(rD, class, stride), which
/// returns the product for indices below 12 and a delta from the instance into the shadow window
/// otherwise.</item>
/// <item><b>step</b>: a pointer walk `addi rP, rP, stride` becomes rP =
/// <see cref="ArrayStepHelper"/>(rP, class, stride, offset), which leaves element 11 of the
/// object for shadow window 0 and moves between windows after that.</item>
/// </list>
/// The list is generated by scripts/mkw100/array_sites.py and named by the project's
/// `translation.array_sites`. Process-wide like <see cref="PlayerSlotStrideSites"/>.
/// </summary>
public sealed class ArrayOverflowSites
{
    public const string IndexScaledHelper = "MKW100_IndexScaled";
    public const string ArrayStepHelper = "MKW100_ArrayStep";
    public const string IndexedBaseHelper = "MKW100_IndexedBase";
    public const string IndexedRestoreHelper = "MKW100_IndexedRestore";
    public const string ObjectAddHelper = "MKW100_ObjectArrayAdd";

    public enum SiteKind { Scale, Step, Index, ObjAdd, CmpImm }

    /// <param name="Offset">scale/step: byte offset from the instance. index: the table's address.</param>
    /// <param name="Shadow">index only: where elements 12.. of the table live.</param>
    /// <param name="Profile">null for the base game; else the translate-mod profile the site is for.</param>
    public sealed record Site(uint Address, int ClassId, SiteKind Kind, int Stride, int Offset,
        uint Shadow = 0, string? Profile = null);

    public static ArrayOverflowSites Current { get; set; } = new(Array.Empty<Site>());

    private readonly FrozenDictionary<uint, Site> _sites;

    public ArrayOverflowSites(IEnumerable<Site> sites) => _sites = sites.ToFrozenDictionary(s => s.Address);

    public int Count => _sites.Count;

    /// <summary>The sites <paramref name="keep"/> accepts.</summary>
    public ArrayOverflowSites Where(Func<Site, bool> keep) => new(_sites.Values.Where(keep));

    public bool TryGet(uint address, out Site site) => _sites.TryGetValue(address, out site!);

    /// <summary>The lifted IR of <paramref name="ins"/>, rewritten when it is a listed site.</summary>
    public IReadOnlyList<IrInstruction> Rewrite(PpcInstruction ins, IReadOnlyList<IrInstruction> ir)
    {
        if (!_sites.TryGetValue(ins.Address, out var site))
            return ir;
        var word = ins.Word;
        var op = (int)(word >> 26);
        var rd = (int)((word >> 21) & 31);
        var ra = (int)((word >> 16) & 31);
        var sh = (int)((word >> 11) & 31);
        var me = (int)((word >> 1) & 31);
        var simm = (int)(short)(word & 0xFFFF);
        string Fail(string why) =>
            throw new InvalidOperationException($"array site 0x{ins.Address:X8} ({ins.Mnemonic}): {why}");

        if (site.Kind == SiteKind.Index)
            return RewriteIndexed(ins, ir, site, Fail);
        if (site.Kind == SiteKind.ObjAdd)
            return RewriteObjectAdd(ins, site, Fail);
        if (site.Kind == SiteKind.CmpImm)
            return RewriteCompareImmediate(ins, ir, site, Fail);

        if (site.Kind == SiteKind.Scale)
        {
            string destination;
            if (op == 7)
                destination = simm == site.Stride ? $"r{rd}" : Fail($"multiplies by {simm}, listed stride {site.Stride}");
            else if (op == 21)
                destination = (1 << sh) == site.Stride && me == 31 - sh && (word & 1) == 0
                    ? $"r{ra}"
                    : Fail($"rlwinm shift {sh}/ME {me} is not a scale by {site.Stride}");
            else
                destination = Fail("not a mulli or rlwinm");
            var call = new IrCall(destination, IndexScaledHelper, new[]
            {
                IrValue.Register(destination), IrValue.Imm(site.ClassId), IrValue.Imm(site.Stride)
            });
            return ir.Append(call).ToArray();
        }

        if (op != 14 || rd != ra || ra == 0 || simm != site.Stride)
            Fail($"not `addi rP, rP, {site.Stride}`");
        return new IrInstruction[]
        {
            new IrCall($"r{rd}", ArrayStepHelper, new[]
            {
                IrValue.Register($"r{ra}"), IrValue.Imm(site.ClassId), IrValue.Imm(site.Stride), IrValue.Imm(site.Offset)
            })
        };
    }

    // X-form indexed loads and stores: lbzx stbx lhzx lhax sthx lwzx stwx lfsx stfsx lfdx stfdx.
    private static readonly HashSet<int> IndexedForms = [87, 215, 279, 343, 407, 23, 151, 535, 663, 599, 727];
    private static readonly HashSet<int> IndexedStores = [215, 407, 151, 663, 727];

    /// <summary>
    /// index: `op rS, rA, rB` on a static table of 12 elements (rA the table, rB the byte offset).
    /// rA is moved to the shadow table around the access when rB reaches element 12, then put back,
    /// so the code's own registers are unchanged afterwards.
    /// </summary>
    private static IReadOnlyList<IrInstruction> RewriteIndexed(
        PpcInstruction ins, IReadOnlyList<IrInstruction> ir, Site site, Func<string, string> fail)
    {
        var word = ins.Word;
        var xo = (int)((word >> 1) & 0x3FF);
        var rs = (int)((word >> 21) & 31);
        var ra = (int)((word >> 16) & 31);
        var rb = (int)((word >> 11) & 31);
        if (word >> 26 != 31 || !IndexedForms.Contains(xo))
            fail("not an X-form indexed load or store");
        if (ra == 0 || ra == rb)
            fail("needs a base register distinct from the index");
        var isFloat = xo is 535 or 663 or 599 or 727;
        if (!IndexedStores.Contains(xo) && !isFloat && rs == ra)
            fail("the load overwrites its base register");
        var args = new[]
        {
            IrValue.Register($"r{ra}"), IrValue.Register($"r{rb}"), IrValue.Imm(site.Offset),
            IrValue.Imm(site.Stride), IrValue.Imm(unchecked((int)site.Shadow))
        };
        var restore = new[]
        {
            IrValue.Register($"r{ra}"), IrValue.Imm(site.Offset), IrValue.Imm(site.Stride),
            IrValue.Imm(unchecked((int)site.Shadow))
        };
        return new IrInstruction[] { new IrCall($"r{ra}", IndexedBaseHelper, args) }
            .Concat(ir)
            .Append(new IrCall($"r{ra}", IndexedRestoreHelper, restore))
            .ToArray();
    }

    /// <summary>
    /// cmpimm: a `cmpwi`/`cmplwi crF, rA, 12` that keeps a pack's code to racers 0..11 (a guard or a
    /// loop bound over a [12] table now shadowed for 12+) compares with the listed value instead
    /// (the site's stride field). Only a compare with 12 is accepted, so a moved site fails loudly.
    /// </summary>
    private static IReadOnlyList<IrInstruction> RewriteCompareImmediate(
        PpcInstruction ins, IReadOnlyList<IrInstruction> ir, Site site, Func<string, string> fail)
    {
        var word = ins.Word;
        var op = (int)(word >> 26);
        if (op is not (10 or 11) || ((word >> 21) & 1) != 0)
            fail("not a 32-bit cmpwi or cmplwi");
        if ((word & 0xFFFF) != 12)
            fail($"compares with {(short)(word & 0xFFFF)}, not 12");
        if (ir.Count != 1 || ir[0] is not IrSetCrField)
            fail("unexpected lifted form");
        var field = (int)((word >> 23) & 7);
        var ra = (int)((word >> 16) & 31);
        return new IrInstruction[]
        {
            new IrSetCrField(field, IrValue.Register($"r{ra}"), IrValue.Imm(site.Stride), op == 10)
        };
    }

    /// <summary>
    /// objadd: `add rD, rObj, rScaled` forming the address of element rScaled / stride of a [12] array
    /// at +offset inside a (non-singleton) object. For elements 12+ rD becomes that object's shadow
    /// table (MKW100_ObjectArrayAdd) minus offset, so the following +offset access lands there.
    /// </summary>
    private static IReadOnlyList<IrInstruction> RewriteObjectAdd(PpcInstruction ins, Site site, Func<string, string> fail)
    {
        var word = ins.Word;
        var rd = (int)((word >> 21) & 31);
        var ra = (int)((word >> 16) & 31);
        var rb = (int)((word >> 11) & 31);
        if (word >> 26 != 31 || ((word >> 1) & 0x1FF) != 266 || (word & 1) != 0 || ((word >> 10) & 1) != 0)
            fail("not `add rD, rObj, rScaled`");
        return new IrInstruction[]
        {
            new IrCall($"r{rd}", ObjectAddHelper, new[]
            {
                IrValue.Register($"r{ra}"), IrValue.Register($"r{rb}"), IrValue.Imm(site.Stride),
                IrValue.Imm(site.Offset), IrValue.Imm(unchecked((int)site.Shadow))
            })
        };
    }

    /// <summary>
    /// One site per line: `0xADDRESS class-id kind stride offset [0xSHADOW] [profile=NAME]`, kind
    /// `scale`, `step` or `index`; offset a 0x-prefixed byte offset from the instance (index: the
    /// table's address, stride its element size, SHADOW required); `#` starts a comment. A site with
    /// a profile only applies when translate-mod runs that profile.
    /// </summary>
    public static ArrayOverflowSites Load(string path)
    {
        var sites = new List<Site>();
        foreach (var (raw, index) in File.ReadLines(path).Select((line, i) => (line, i)))
        {
            var text = raw.Split('#', 2)[0].Trim();
            if (text.Length == 0)
                continue;
            var all = text.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries);
            FormatException Bad(string why) => new($"{path}:{index + 1}: {why}: '{text}'");
            var profile = all.Where(f => f.StartsWith("profile=", StringComparison.Ordinal))
                .Select(f => f["profile=".Length..]).SingleOrDefault();
            var fields = all.Where(f => !f.StartsWith("profile=", StringComparison.Ordinal)).ToArray();
            if (fields.Length < 5)
                throw Bad("expected address, class id, kind, stride, offset");
            var kind = fields[2] switch
            {
                "scale" => SiteKind.Scale,
                "step" => SiteKind.Step,
                "index" => SiteKind.Index,
                "objadd" => SiteKind.ObjAdd,
                "cmpimm" => SiteKind.CmpImm,
                _ => throw Bad("kind must be scale, step, index, objadd or cmpimm")
            };
            var shadowed = kind is SiteKind.Index or SiteKind.ObjAdd;
            if (fields.Length != (shadowed ? 6 : 5))
                throw Bad(shadowed ? "index and objadd sites need a shadow address" : "too many fields");
            sites.Add(new Site(Hex(fields[0]) ?? throw Bad("bad address"),
                int.Parse(fields[1], CultureInfo.InvariantCulture), kind,
                int.Parse(fields[3], CultureInfo.InvariantCulture),
                unchecked((int)(Hex(fields[4]) ?? throw Bad("bad offset"))),
                shadowed ? Hex(fields[5]) ?? throw Bad("bad shadow") : 0,
                profile));
        }
        return new ArrayOverflowSites(sites);
    }

    private static uint? Hex(string text) =>
        text.StartsWith("0x", StringComparison.OrdinalIgnoreCase)
        && uint.TryParse(text.AsSpan(2), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var value)
            ? value
            : null;
}
